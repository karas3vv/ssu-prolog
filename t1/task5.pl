    родитель(Кто, Кого),
    мужчина(Кто).

сын(Кто, Кого) :-
    родитель(Кого, Кто),
    мужчина(Кто).

дочь(Кто, Кого) :-
    родитель(Кого, Кто),
    женщина(Кто).

дед(Прародитель, Потомок) :-
