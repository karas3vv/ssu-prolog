дети_родителей(Кто, Кого) :-
    (
        (отец(Отец, Кто), отец(Отец, Кого))
        ;
        (
            мать(Мать, Кто),
            мать(Мать, Кого),
            \+ (отец(Отец, Кто), отец(Отец, Кого))
        )
    ),
    Кто \= Кого.

брат(Кто, Кого) :-
    мужчина(Кто),
    дети_родителей(Кто, Кого).

сестра(Кто, Кого) :-
    женщина(Кто),
    дети_родителей(Кто, Кого).

племянница(Кто, Кого) :-
    дети_родителей(Родитель, Кого),
    дочь(Кто, Родитель).

родители(Родитель1, Родитель2) :- 
    (
    (отец(Родитель1, Ребенок), мать(Родитель2, Ребенок)), 
    \+ (отец(Родитель2, Ребенок), мать(Родитель1, Ребенок))
    ),  
    Родитель1\==Родитель2.

