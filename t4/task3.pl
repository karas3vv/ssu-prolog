ханой(1, Откуда, Куда, _) :-
    write('Переместить диск с '),
    write(Откуда),
    write(' на '),
    write(Куда),
    nl.

ханой(N, Откуда, Куда, Вспомогательный) :-
    N > 1,
    N1 is N - 1,

    ханой(N1, Откуда, Вспомогательный, Куда),

    write('Переместить диск с '),
    write(Откуда),
    write(' на '),
    write(Куда),
    nl,

    ханой(N1, Вспомогательный, Куда, Откуда).

