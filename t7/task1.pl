:- encoding(utf8).
:- dynamic верно/1, ложно/1.

% ответы очищаются перед диалогом и после его завершения.
цель :-
    очистить,
    ( спорт(Название) ->
        format('загаданный вид спорта — ~w!~n', [Название])
    ; writeln('к сожалению, этот вид спорта мне не известен.')
    ),
    очистить.

