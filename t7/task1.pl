% экспертная система "вид спорта".
% запуск: ?- цель.
% ответы: да. или нет.

:- encoding(utf8).
:- dynamic ответ/2.

цель :-
    setup_call_cleanup(
        retractall(ответ(_, _)),
        (
            спорт(Название) ->
                format('загаданный вид спорта — ~w!~n', [Название])
            ;
                writeln('к сожалению, этот вид спорта мне не известен.')
        ),
        retractall(ответ(_, _))
    ).

