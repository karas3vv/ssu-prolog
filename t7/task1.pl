% Сначала проверяем сохранённый ответ. Если ответа нет — спрашиваем.
свойство(Вопрос) :-
    верно(Вопрос), !.
свойство(Вопрос) :-
    \+ ложно(Вопрос),
    узнать(Вопрос, Ответ),
    Ответ = да.

нет_свойства(Вопрос) :-
    ложно(Вопрос), !.
нет_свойства(Вопрос) :-
    \+ верно(Вопрос),
    узнать(Вопрос, Ответ),
    Ответ = нет.

узнать(Вопрос, Ответ) :-
    format('~w? (да./нет.)~n', [Вопрос]),
    read(Ввод),
    ( Ввод == да -> Ответ = да
    ; Ввод == нет -> Ответ = нет
    ; Ввод == end_of_file ->
        очистить,
        throw(error(unexpected_end_of_file, узнать/2))
    ; writeln('введите да. или нет.'),
      узнать(Вопрос, Ответ)
    ),
    запомнить(Вопрос, Ответ).

запомнить(Вопрос, да) :-
    ( верно(Вопрос) -> true ; assertz(верно(Вопрос)) ).
запомнить(Вопрос, нет) :-
    ( ложно(Вопрос) -> true ; assertz(ложно(Вопрос)) ).

% retractall удаляет все ответы и успешно завершает очистку.
очистить :-
    retractall(верно(_)),
    retractall(ложно(_)).

