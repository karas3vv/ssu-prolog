% правила нижнего уровня.
это(командный_с_мячом) :-
    свойство('это командная игра с мячом').

это(с_ракеткой) :-
    свойство('используют ракетку').

это(зимний) :-
    свойство('соревнования проходят на снегу или льду').

это(единоборство) :-
    свойство('это поединок двух соперников').

это(водный) :-
    свойство('соревнования проходят в воде').

это(на_велосипеде) :-
    свойство('используют велосипед').

свойство(Вопрос) :-
    проверить(Вопрос, да).

нет_свойства(Вопрос) :-
    проверить(Вопрос, нет).

проверить(Вопрос, Ожидаемый) :-
    (
        ответ(Вопрос, Сохранённый) ->
            Фактический = Сохранённый
        ;
            спросить(Вопрос, Фактический),
            assertz(ответ(Вопрос, Фактический))
    ),
    Фактический = Ожидаемый.

спросить(Вопрос, Ответ) :-
    format('~w? (да./нет.)~n', [Вопрос]),
    read(Ввод),
    (
        (Ввод == да ; Ввод == нет) ->
            Ответ = Ввод
        ;
        Ввод == end_of_file ->
            throw(error(unexpected_end_of_file, спросить/2))
        ;
            writeln('введите да. или нет.'),
            спросить(Вопрос, Ответ)
    ).